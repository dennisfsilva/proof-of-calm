// A linear congruential generator, so a seed always gives the same texts.
function* texts(seed: number, count: number) {
  let state = seed;
  const next = () => {
    state = (state * 1103515245 + 12345) & 0x7fffffff;
    return state / 0x7fffffff;
  };
  for (let index = 0; index < count; index++) {
    let text = '';
    for (let words = 1 + Math.floor(next() * 9); words > 0; words--) {
      const token = TOKENS[Math.floor(next() * TOKENS.length)] ?? '';
      text += /^[.,;:!?…)»\n]/.test(token)
        ? token
        : (text && !/[\n(«“"]$/.test(text) && next() < 0.9 ? ' ' : '') + token;
    }
    yield text;
  }
}
