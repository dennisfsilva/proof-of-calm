const mainBetween = (alternatives: readonly string[], flags = 'giu') =>
  new RegExp(`(?<![\\p{L}\\p{N}])(${alternatives.join('|')})(?![\\p{L}\\p{N}])`, flags);
const mainLiteral = (phrase: string) => phrase.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
const MAIN_ADVICE = mainBetween(MAIN.advice);
const MAIN_FILLER = mainBetween(MAIN.filler);
const MAIN_ALLOWED = mainBetween([...MAIN.allow].sort((a, b) => b.length - a.length).map(mainLiteral));
const MAIN_PERCENT = String.raw`\d+(?:[.,]\d+)?\s?%`;
const MAIN_GAIN = '(?:returns?|gains?|profits?|yields?)';
const MAIN_RETURN = new RegExp(`${MAIN_PERCENT}\\s*${MAIN_GAIN}|${MAIN_GAIN}\\s+(?:of\\s+)?${MAIN_PERCENT}`, 'giu');
const MAIN_ASSET = mainBetween(
  ['bitcoin', 'ether(?:eum)?', 'solana', 'chainlink', 'crypto(?:currenc(?:y|ies))?'],
  'iu',
);
const MAIN_TICKER = mainBetween(['BTC', 'ETH', 'SOL', 'LINK'], 'u');
const MAIN_IMPERATIVE = /^\s*(buy|sell|hold|invest|get|grab|kaufe?n?|compre|venda)(?![\p{L}\p{N}])(?!\s+days?\b)/iu;
const mainAll = (pattern: RegExp, text: string, rule: Finding['rule']): Finding[] =>
  [...text.matchAll(pattern)].map((match) => ({ rule, match: match[0] }));
function findBannedMain(text: string): Finding[] {
  const kept = text.replace(MAIN_ALLOWED, ' ');
  const imperatives = kept
    .split(/[.!?\n]+/)
    .filter((sentence) => MAIN_IMPERATIVE.test(sentence) && (MAIN_ASSET.test(sentence) || MAIN_TICKER.test(sentence)))
    .map((sentence): Finding => ({ rule: 'imperative', match: sentence.trim() }));
  return [
    ...mainAll(MAIN_ADVICE, kept, 'advice'),
    ...mainAll(MAIN_FILLER, kept, 'filler'),
    ...mainAll(MAIN_RETURN, kept, 'return-percentage'),
    ...imperatives,
  ];
}
const contains = (now: readonly Finding[], before: Finding) =>
  now.some((finding) => finding.rule === before.rule && finding.match.includes(before.match));

