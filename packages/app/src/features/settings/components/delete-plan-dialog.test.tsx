import { exportBackup, liveEntries } from '@proofofcalm/core';
import { aPlan } from '@proofofcalm/core/testing';
import { Toaster } from '@proofofcalm/ui/components/toast';
import { act, cleanup, fireEvent, render, screen, waitFor, within } from '@testing-library/react';
import { afterEach, beforeAll, describe, expect, it, onTestFinished, vi } from 'vitest';
import { EMPTY_SNAPSHOT, memoryPlanStore } from '../../../lib/adapters/memory-store';
import { I18nProvider } from '../../../lib/i18n';
import { NavigationProvider } from '../../../lib/navigation';
import type { PlanStore, Platform } from '../../../lib/ports';
import { ServicesProvider } from '../../../lib/services';
import { fixtureSnapshot } from '../../../lib/services/fixtures';
import { createTestServices, recordingPlatform } from '../../../lib/services/testing';
import errors from '../../../messages/en/errors.json';
import settings from '../../../messages/en/settings.json';
import { DataSection } from './data-section';
import { choose, NOW } from './data-section.testing';

// "Delete everything" in the data section: the dialog, the delete at once, the toast's Undo and its refusal,
// and where the focus goes (docs/CONTENT-STYLE.md "Delete the plan", ADR-0019 Readings).

// The undo's focus move brings Delete everything into view; jsdom has no `scrollIntoView`.
beforeAll(() => {
  Element.prototype.scrollIntoView = vi.fn();
});
afterEach(cleanup);

async function mount(planStore: PlanStore, platform?: Platform) {
  const services = createTestServices({ planStore, ...(platform && { platform }) });
  render(
    <NavigationProvider location="memory" initialPath="/settings">
      <ServicesProvider services={services}>
        <I18nProvider messages={{ settings, errors }}>
          <Toaster closeLabel="Close" toastManager={services.toasts}>
            <DataSection />
          </Toaster>
        </I18nProvider>
      </ServicesProvider>
    </NavigationProvider>,
  );
  await act(() => services.start());
  return services;
}

async function openDialog() {
  fireEvent.click(screen.getByRole('button', { name: 'Delete everything' }));
  return screen.findByRole('dialog');
}

/** A store whose wipe waits until `release` lets it run, or `fail` rejects it. */
function held(backing: PlanStore) {
  let release = () => {};
  let fail = () => {};
  const gate = new Promise<void>((resolve, reject) => {
    release = resolve;
    fail = () => reject(new Error('blocked'));
  });
  const planStore: PlanStore = {
    ...backing,
    wipe: async () => {
      await gate;
      return backing.wipe();
    },
  };
  return { planStore, release: () => release(), fail: () => fail() };
}

/** Focuses and presses the dialog's Delete everything, leaving the delete running. */
async function pressDelete(dialog: HTMLElement) {
  const confirm = within(dialog).getByRole('button', { name: 'Delete everything' });
  confirm.focus();
  await act(async () => void fireEvent.click(confirm));
  return confirm;
}

describe('DeletePlanDialog', () => {
  it('names the plan and its entries, offers a copy first, and opens on the safe button', async () => {
    const snapshot = fixtureSnapshot();
    await mount(memoryPlanStore(snapshot));
    const dialog = await openDialog();
    const count = liveEntries(snapshot.entries).length;
    expect(within(dialog).getByRole('heading').textContent).toBe(`Delete this plan and its ${count} entries?`);
    expect(within(dialog).getByText('Export a copy first if you want to keep them.')).toBeTruthy();
    // The export line sits right above the control that opens the dialog: once per path (docs/LEGAL.md §4).
    expect(within(dialog).queryByText(/Exports are generated by/)).toBeNull();
    expect(within(dialog).queryByRole('link')).toBeNull();
    const buttons = within(dialog)
      .getAllByRole('button')
      .map((button) => button.textContent);
    expect(buttons).toEqual(['Keep this plan', 'Export a copy first', 'Delete everything']);
    await waitFor(() => expect(document.activeElement?.textContent).toBe('Keep this plan'));
  });

  it('says "keep it" for a plan with no entries', async () => {
    await mount(memoryPlanStore({ ...EMPTY_SNAPSHOT, plan: aPlan() }));
    const dialog = await openDialog();
    expect(within(dialog).getByRole('heading').textContent).toBe('Delete this plan?');
    expect(within(dialog).getByText('Export a copy first if you want to keep it.')).toBeTruthy();
  });

  it('saves the JSON backup, the copy an import can read back, and keeps the plan', async () => {
    const platform = recordingPlatform();
    const planStore = memoryPlanStore(fixtureSnapshot());
    await mount(planStore, platform);
    const dialog = await openDialog();
    await act(async () => fireEvent.click(within(dialog).getByRole('button', { name: 'Export a copy first' })));
    expect(platform.calls.downloads.map(({ type }) => type)).toEqual(['application/json']);
    expect(planStore.current().plan).not.toBeNull();
    expect(screen.getByRole('dialog')).toBe(dialog);
  });

  it('deletes at once, moves the focus to the heading, and Undo puts every row back', async () => {
    const snapshot = fixtureSnapshot();
    const planStore = memoryPlanStore(snapshot);
    const services = await mount(planStore);
    const before = planStore.current();
    const dialog = await openDialog();
    await act(async () => fireEvent.click(within(dialog).getByRole('button', { name: 'Delete everything' })));
    expect(planStore.current().plan).toBeNull();
    expect(services.domain.store.getState().snapshot.plan).toBeNull();
    await waitFor(() => expect(screen.queryByRole('dialog')).toBeNull());
    await waitFor(() => expect(document.activeElement).toBe(screen.getByRole('heading', { name: 'Your data' })));
    expect(screen.getByText('Plan deleted.')).toBeTruthy();
    await act(async () => fireEvent.click(screen.getByRole('button', { name: 'Undo' })));
    await waitFor(() => expect(planStore.current()).toEqual(before));
    expect(services.domain.store.getState().snapshot.plan).toEqual(snapshot.plan);
    expect(screen.getByRole('button', { name: 'Delete everything' })).toBeTruthy();
  });

  /** The element before the toast in the Tab order (the Learn link in the app); the section has none without a plan. */
  const tabbedFrom = () => {
    const link = document.body.appendChild(document.createElement('a'));
    link.href = '/learn';
    onTestFinished(() => link.remove());
    return link;
  };

  // docs/DESIGN.md §6: the toast leaves the focus to the Undo, which puts it on Delete everything once the rows
  // are back, never on the heading or on the element Tab reached the toast from; a refusal gives it back there.
  it('Undo puts the focus on Delete everything, from the heading or after Tab', async () => {
    await mount(memoryPlanStore(fixtureSnapshot()));
    for (const reach of ['heading', 'Tab'] as const) {
      const dialog = await openDialog();
      await act(async () => fireEvent.click(within(dialog).getByRole('button', { name: 'Delete everything' })));
      await waitFor(() => expect(document.activeElement).toBe(screen.getByRole('heading', { name: 'Your data' })));
      const undo = screen.getByRole('button', { name: 'Undo' });
      if (reach === 'Tab') {
        tabbedFrom().focus();
        undo.focus();
      }
      await act(async () => fireEvent.click(undo));
      await waitFor(() =>
        expect(document.activeElement).toBe(screen.getByRole('button', { name: 'Delete everything' })),
      );
    }
  });

  it('a refused Undo reached by Tab gives the focus back where it came from', async () => {
    const planStore = memoryPlanStore(fixtureSnapshot());
    await mount(planStore);
    const dialog = await openDialog();
    await act(async () => fireEvent.click(within(dialog).getByRole('button', { name: 'Delete everything' })));
    await planStore.write({ plan: aPlan() });
    const link = tabbedFrom();
    const undo = screen.getByRole('button', { name: 'Undo' });
    link.focus();
    undo.focus();
    await act(async () => fireEvent.click(undo));
    await screen.findByText(
      'Another browser tab started or imported a plan after you deleted this one, so it stays deleted.',
    );
    expect(document.activeElement).toBe(link);
  });

  it('deletes once on a double press, so the one Undo puts the plan and every entry back', async () => {
    const backing = memoryPlanStore(fixtureSnapshot());
    const before = backing.current();
    let release = () => {};
    const held = new Promise<void>((resolve) => {
      release = resolve;
    });
    await mount({
      ...backing,
      wipe: async () => {
        await held;
        return backing.wipe();
      },
    });
    const dialog = await openDialog();
    const confirm = within(dialog).getByRole('button', { name: 'Delete everything' });
    fireEvent.click(confirm);
    fireEvent.click(confirm);
    await act(async () => release());
    await waitFor(() => expect(screen.queryByRole('dialog')).toBeNull());
    const undo = screen.getAllByRole('button', { name: 'Undo' });
    expect(undo).toHaveLength(1);
    await act(async () => fireEvent.click(undo[0] as HTMLElement));
    await waitFor(() => expect(backing.current()).toEqual(before));
  });

  it('keeps the plan another tab started after the delete, and says why the Undo did nothing', async () => {
    const planStore = memoryPlanStore(fixtureSnapshot());
    await mount(planStore);
    const dialog = await openDialog();
    await act(async () => fireEvent.click(within(dialog).getByRole('button', { name: 'Delete everything' })));
    const theirs = aPlan();
    await planStore.write({ plan: theirs });
    await act(async () => fireEvent.click(screen.getByRole('button', { name: 'Undo' })));
    await screen.findByText(
      'Another browser tab started or imported a plan after you deleted this one, so it stays deleted.',
    );
    expect(planStore.current().plan).toEqual(theirs);
    expect(planStore.current().entries).toEqual([]);
  });

  it('keeps the dialog and the plan when the delete fails, and says so', async () => {
    const backing = memoryPlanStore(fixtureSnapshot());
    await mount({
      ...backing,
      wipe: () => Promise.reject(new Error('blocked')),
    });
    const dialog = await openDialog();
    await act(async () => fireEvent.click(within(dialog).getByRole('button', { name: 'Delete everything' })));
    expect(within(dialog).getByRole('alert').textContent).toMatch(/went wrong|try again/i);
    expect(backing.current().plan).not.toBeNull();
  });

  // docs/DESIGN.md §6: Delete stays focusable while the delete runs, so a failed delete keeps the focus on it
  // while the alert line speaks, never on the body.
  it('keeps the focus on Delete while the delete runs and after it fails', async () => {
    const backing = memoryPlanStore(fixtureSnapshot());
    let fail = () => {};
    const held = new Promise<never>((_, reject) => {
      fail = () => reject(new Error('blocked'));
    });
    await mount({ ...backing, wipe: () => held });
    const dialog = await openDialog();
    const confirm = within(dialog).getByRole('button', { name: 'Delete everything' });
    confirm.focus();
    await act(async () => void fireEvent.click(confirm));
    expect(confirm.hasAttribute('disabled')).toBe(false);
    expect(confirm.getAttribute('aria-disabled')).toBe('true');
    expect(document.activeElement).toBe(confirm);
    await act(async () => fail());
    expect(within(dialog).getByRole('alert').textContent).toMatch(/went wrong|try again/i);
    expect(confirm.getAttribute('aria-disabled')).not.toBe('true');
    expect(document.activeElement).toBe(confirm);
  });

  // An Escape or Keep while the delete runs neither closes the dialog nor moves the focus: the delete's end
  // closes it (focus on the heading), or its failure speaks inside it (docs/DESIGN.md §6).
  it('keeps the dialog open on an Escape while the delete runs, with the focus on Delete', async () => {
    const { planStore, release } = held(memoryPlanStore(fixtureSnapshot()));
    await mount(planStore);
    const dialog = await openDialog();
    const confirm = await pressDelete(dialog);
    fireEvent.keyDown(confirm, { key: 'Escape' });
    await act(async () => {});
    expect(screen.getByRole('dialog')).toBe(dialog);
    expect(document.activeElement).toBe(confirm);
    await act(async () => release());
    await waitFor(() => expect(screen.queryByRole('dialog')).toBeNull());
    await waitFor(() => expect(document.activeElement).toBe(screen.getByRole('heading', { name: 'Your data' })));
    expect(screen.getByText('Plan deleted.')).toBeTruthy();
  });

  it('does nothing on Keep while the delete runs, and keeps the focus on it', async () => {
    const { planStore, release } = held(memoryPlanStore(fixtureSnapshot()));
    await mount(planStore);
    const dialog = await openDialog();
    await pressDelete(dialog);
    const keep = within(dialog).getByRole('button', { name: 'Keep this plan' });
    expect(keep.getAttribute('aria-disabled')).toBe('true');
    keep.focus();
    fireEvent.click(keep);
    await act(async () => {});
    expect(screen.getByRole('dialog')).toBe(dialog);
    expect(document.activeElement).toBe(keep);
    await act(async () => release());
    await waitFor(() => expect(screen.queryByRole('dialog')).toBeNull());
    await waitFor(() => expect(document.activeElement).toBe(screen.getByRole('heading', { name: 'Your data' })));
  });

  it('shows a delete that fails after an Escape in the dialog that stayed open', async () => {
    const backing = memoryPlanStore(fixtureSnapshot());
    const { planStore, fail } = held(backing);
    await mount(planStore);
    const dialog = await openDialog();
    const confirm = await pressDelete(dialog);
    fireEvent.keyDown(confirm, { key: 'Escape' });
    await act(async () => fail());
    expect(screen.getByRole('dialog')).toBe(dialog);
    expect(within(dialog).getByRole('alert').textContent).toMatch(/went wrong|try again/i);
    expect(document.activeElement).toBe(confirm);
    expect(backing.current().plan).not.toBeNull();
  });

  it('after a delete through an Escape and its Undo, Keep gives the focus back to Delete everything', async () => {
    const { planStore, release } = held(memoryPlanStore(fixtureSnapshot()));
    await mount(planStore);
    const first = await openDialog();
    const confirm = await pressDelete(first);
    fireEvent.keyDown(confirm, { key: 'Escape' });
    await act(async () => release());
    await waitFor(() => expect(screen.queryByRole('dialog')).toBeNull());
    await act(async () => fireEvent.click(screen.getByRole('button', { name: 'Undo' })));
    const reopen = await screen.findByRole('button', { name: 'Delete everything' });
    reopen.focus();
    const dialog = await openDialog();
    await waitFor(() => expect(document.activeElement?.textContent).toBe('Keep this plan'));
    fireEvent.click(within(dialog).getByRole('button', { name: 'Keep this plan' }));
    await waitFor(() => expect(screen.queryByRole('dialog')).toBeNull());
    await waitFor(() => expect(document.activeElement).toBe(screen.getByRole('button', { name: 'Delete everything' })));
  });

  it('offers nothing to delete without a plan', async () => {
    await mount(memoryPlanStore(EMPTY_SNAPSHOT));
    expect(screen.queryByRole('button', { name: 'Delete everything' })).toBeNull();
  });

  it('opens Replace everything on the safe button too', async () => {
    const snapshot = fixtureSnapshot();
    if (snapshot.plan === null) throw new Error('the fixture has a plan');
    await mount(memoryPlanStore(snapshot));
    await choose(JSON.stringify(exportBackup(snapshot.plan, snapshot.entries.slice(0, 2), NOW)));
    fireEvent.click(screen.getByRole('button', { name: 'Replace everything' }));
    await screen.findByRole('dialog');
    await waitFor(() => expect(document.activeElement?.textContent).toBe('Keep this plan'));
  });
});
