import { exportBackup, type Instant } from '@proofofcalm/core';
import type { Meta, StoryObj } from '@storybook/react-vite';
import { expect, userEvent, waitFor, within } from 'storybook/test';
import twoCoins from '../../../../../core/test/golden/two-coins.json';
import { fixtureNowMs, fixtureSnapshot } from '../../../lib/services/fixtures';
import { DataSection } from './data-section';

// The data section with the fixture plan, with entries from a newer version left out of the exports, before a
// plan exists, Replace everything over a plan, which asks first, and a file from the DCA plan page with no plan, chosen or pasted, which asks for the country; the test projects of vitest.config.ts render each at 360 and 1280 px, light and
// dark, with axe.
const withPlan = { path: '/settings', snapshot: fixtureSnapshot(), nowMs: fixtureNowMs('buy') };

function backupFile(): File {
  const { plan, entries } = fixtureSnapshot();
  if (plan === null) throw new Error('the fixture has a plan');
  const backup = exportBackup(plan, entries.slice(0, 2), '2026-10-20T10:00:00.000Z' as Instant);
  return new File([JSON.stringify(backup)], 'proof-of-calm-backup-2026-10-20.json', { type: 'application/json' });
}

const meta = {
  title: 'Features/Settings/DataSection',
  component: DataSection,
  parameters: { path: '/settings' },
} satisfies Meta<typeof DataSection>;

export default meta;

type Story = StoryObj<typeof meta>;

export const WithPlan: Story = {
  parameters: withPlan,
  play: async ({ canvas }) => {
    await waitFor(() => expect(canvas.getByRole('button', { name: 'Export JSON backup' })).toBeVisible());
    await expect(canvas.getByRole('button', { name: 'Export CSV log' })).toBeVisible();
    await expect(
      canvas.getByText(/^Exports are generated by Proof of Calm from your own entries; not advice\./),
    ).toBeVisible();
    await expect(canvas.getByRole('link', { name: 'Risk disclosure' })).toHaveAttribute('href', '/risk');
    // Headings carry the heading tracking, −0.01 em (docs/DESIGN.md §5), as onboarding's do.
    for (const heading of canvas.getAllByRole('heading')) {
      const style = getComputedStyle(heading);
      await expect(px(style.letterSpacing)).toBeCloseTo(-0.01 * px(style.fontSize), 3);
    }
  },
};

export const NewerEntriesLeftOut: Story = {
  parameters: { ...withPlan, snapshot: { ...fixtureSnapshot(), newer: { plans: 0, entries: 2 } } },
  play: async ({ canvas }) => {
    await waitFor(() =>
      expect(
        canvas.getByText(
          'Exports leave out 2 entries saved by a newer version of Proof of Calm. Reload the page, then export to include them.',
        ),
      ).toBeVisible(),
    );
    await expect(canvas.getByRole('button', { name: 'Export JSON backup' })).toBeVisible();
    await expect(canvas.getByRole('button', { name: 'Export CSV log' })).toBeVisible();
  },
};

export const NoPlan: Story = {
  play: async ({ canvas }) => {
    await waitFor(() => expect(canvas.getByText(/^Nothing to export yet\./)).toBeVisible());
    await expect(canvas.queryByRole('button', { name: 'Export JSON backup' })).toBeNull();
  },
};

export const ReplaceAsksFirst: Story = {
  parameters: withPlan,
  play: async ({ canvas, canvasElement }) => {
    await waitFor(() => expect(canvas.getByRole('button', { name: 'Export JSON backup' })).toBeVisible());
    await userEvent.upload(canvas.getByLabelText('Choose a file'), backupFile());
    await userEvent.click(await canvas.findByRole('button', { name: 'Replace everything' }));
    const document = within(canvasElement.ownerDocument.body);
    const dialog = await document.findByRole('dialog');
    await expect(dialog).toHaveAccessibleName(/^Replace this plan and its \d+ entries\?$/);
    // The dialog fades in (Base UI's starting style); visibility settles once the transition ends.
    await waitFor(() => expect(within(dialog).getByRole('button', { name: 'Export a copy first' })).toBeVisible());
  },
};

export const PrototypeAsksForCountry: Story = {
  play: async ({ canvas }) => {
    await waitFor(() => expect(canvas.getByText(/^Nothing to export yet\./)).toBeVisible());
    const file = new File([JSON.stringify(twoCoins.state)], 'DCA-Plan.json', { type: 'application/json' });
    await userEvent.upload(canvas.getByLabelText('Choose a file'), file);
    await expect(
      await canvas.findByText('DCA-Plan.json, exported from the DCA plan page. Purchases in this file: 18.'),
    ).toBeVisible();
    await expect(await canvas.findByRole('heading', { name: 'Where do you live?' })).toBeVisible();
    await expect(canvas.queryByRole('button', { name: 'Import this backup' })).toBeNull();
  },
};

export const PrototypePasted: Story = {
  play: async ({ canvas }) => {
    await waitFor(() => expect(canvas.getByText(/^Nothing to export yet\./)).toBeVisible());
    await userEvent.click(canvas.getByRole('textbox', { name: 'Paste a backup or an export from the DCA plan page' }));
    await userEvent.paste(JSON.stringify(twoCoins.state, null, 2));
    // A long paste scrolls inside the box, a few lines tall, so Read stays just below it.
    const box = canvas.getByRole('textbox', { name: 'Paste a backup or an export from the DCA plan page' });
    const read = canvas.getByRole('button', { name: 'Read the pasted text' });
    await expect(box.scrollHeight).toBeGreaterThan(box.clientHeight);
    const lines =
      (read.getBoundingClientRect().top - box.getBoundingClientRect().top) / px(getComputedStyle(box).lineHeight);
    await expect(lines).toBeLessThan(10);
    await userEvent.click(read);
    await expect(
      await canvas.findByText('Pasted text, exported from the DCA plan page. Purchases in this text: 18.'),
    ).toBeVisible();
    await expect(
      canvas.getByRole('textbox', { name: 'Paste a backup or an export from the DCA plan page' }),
    ).toHaveValue('');
    // The country step takes the focus when it appears (docs/DESIGN.md §6).
    const intro = await canvas.findByText(/^Files from the DCA plan page have no country\./);
    await waitFor(() => expect(intro).toHaveFocus());
  },
};

// A computed CSS length in pixels.
function px(value: string) {
  return Number(value.replace('px', ''));
}
