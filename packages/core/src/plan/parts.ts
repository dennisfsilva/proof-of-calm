// Planned parts and the one-tap fill (docs/DOMAIN.md §3.4): "Bought as planned" creates the planned
// entries with the day's prices as an editable draft; typing exact units stays available.
import { type CalendarDate, compareInstants, type Instant } from '../dates/calendar';
import { transactionKey } from '../log/group';
import { MINOR_UNITS } from '../money/currency';
import { compare, isPositive, type Money, type Percent, sum, type Units, unitsFor } from '../money/decimal';
import { splitLargestRemainder } from '../money/split';
import type { Entry } from '../schema/entry';
import type { CoinId, EntityId } from '../schema/ids';
import type { Plan } from '../schema/plan';
import type { PriceSnapshot } from '../schema/prices';
import { type Action, liveEntries } from './statuses';

export type PlannedPart = { readonly coin: CoinId; readonly amount: Money };

/**
 * `total` split over the coins with a share above zero, in plan order, so that the parts sum to
 * exactly `total` at the pay currency's minor unit (largest remainder; ties to the earlier coin).
 */
export function plannedParts(plan: Plan, total: Money): PlannedPart[] {
  const funded: { coin: CoinId; share: Percent }[] = [];
  for (const coin of plan.coins) {
    const share = plan.split[coin.id];
    if (share !== undefined && isPositive(share)) funded.push({ coin: coin.id, share });
  }
  const amounts = splitLargestRemainder(
    total,
    funded.map((part) => part.share),
    MINOR_UNITS[plan.payCurrency],
  );
  return funded.map((part, index) => ({ coin: part.coin, amount: amounts[index] as Money }));
}

/**
 * Whether two lists of parts are the same: the same coins in the same order, amounts equal by value
 * (70 and 70.00 are equal). The one tap compares the parts a screen showed with the plan as stored (§6).
 */
export function sameParts(a: readonly PlannedPart[], b: readonly PlannedPart[]): boolean {
  return (
    a.length === b.length &&
    a.every((part, index) => {
      const other = b[index] as PlannedPart;
      return part.coin === other.coin && compare(part.amount, other.amount) === 0;
    })
  );
}

/** An entry before saving: units are missing where the day's price is (the shell asks for them). */
export type EntryDraft = Omit<Entry, 'units'> & { readonly units: Units | null };

export type OneTapInput = {
  readonly plan: Plan;
  readonly action: Action;
  readonly prices: PriceSnapshot | null;
  readonly today: CalendarDate;
  /** The transaction's fee, split across the entries by amount; usually `defaultFee(entries)`. */
  readonly fee: Money | null;
  /** One id per planned part, generated by the shell. */
  readonly ids: readonly EntityId[];
  readonly now: Instant;
  /** The venue of the last entry, remembered by the log form (docs/ROADMAP.md M1). */
  readonly venue: string | null;
};

export function oneTapEntries(input: OneTapInput): EntryDraft[] {
  const { plan, action, prices, today, fee, ids, now, venue } = input;
  // A total too small to give every coin a cent leaves zero parts; a zero buy cannot be recorded.
  const parts = plannedParts(plan, action.plannedAmount).filter((part) => isPositive(part.amount));
  if (ids.length < parts.length) throw new RangeError(`${parts.length} ids needed, ${ids.length} given`);
  const minorDigits = MINOR_UNITS[plan.payCurrency];
  const fees =
    fee === null
      ? null
      : splitLargestRemainder(
          fee,
          parts.map((part) => part.amount),
          minorDigits,
        );
  return parts.map((part, index): EntryDraft => {
    const coin = plan.coins.find((candidate) => candidate.id === part.coin);
    const price = prices?.prices[part.coin]?.[plan.payCurrency];
    const units =
      coin !== undefined && price !== undefined && isPositive(price)
        ? unitsFor(part.amount, price, coin.decimals)
        : null;
    return {
      id: ids[index] as EntityId,
      kind: action.kind,
      date: today,
      coin: part.coin,
      amount: part.amount,
      // An amount too small for the coin's decimals rounds to zero units; the user types them instead.
      units: units !== null && isPositive(units) ? units : null,
      fee: fees === null ? null : (fees[index] as Money),
      note: '',
      slot: action.kind === 'dca' ? action.slot : null,
      venue,
      source: 'one-tap',
      createdAt: now,
      updatedAt: now,
      deletedAt: null,
    };
  });
}

/** One-tap works when at least one coin has a price; otherwise the form opens with the amounts filled. */
export function canOneTap(drafts: readonly EntryDraft[]): boolean {
  return drafts.some((draft) => draft.units !== null);
}

/**
 * The fee of the most recent transaction that recorded one (its entries' shares summed), else null.
 * It is a transaction's fee, not one entry's share, because the one-tap fill splits it again.
 */
export function defaultFee(entries: readonly Entry[]): Money | null {
  const withFee = liveEntries(entries).filter((entry) => entry.fee !== null);
  let latest: Entry | null = null;
  for (const entry of withFee) {
    if (
      latest === null ||
      entry.date > latest.date ||
      (entry.date === latest.date && compareInstants(entry.createdAt, latest.createdAt) > 0)
    ) {
      latest = entry;
    }
  }
  if (latest === null) return null;
  const key = transactionKey(latest);
  return sum(withFee.filter((entry) => transactionKey(entry) === key).map((entry) => entry.fee as Money));
}
